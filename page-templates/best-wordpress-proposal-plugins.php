			<h3 class="section-subheading">Sprout Invoices</h3>
			<p class="section-lede">Despite showing up in "proposal plugin" searches, this is really an estimates-and-invoicing tool first — unlimited invoices, estimates, and clients on the free WordPress.org version, with solid multi-currency and tax add-on support. Recurring invoices, client dashboards, and Stripe require a paid licence; third-party sources disagree on the exact price (figures from $39.50 to $59.25/year turn up depending on the source), and the vendor's own pricing page appears stale, so confirm directly with Sprout before buying. If what you actually need is invoicing more than a polished sales proposal, it's worth a look — just don't expect e-signature or a client portal.</p>

